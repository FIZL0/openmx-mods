//! C5: the ultra map, every game's giant map joined whole (`worlds/world_ultra.json`, `stitch::ultra`).
//!
//! On generated worlds: each world's tiles and joins are its own, moved; where the new ground meets a
//! world's edge, height and slope are continuous; a world with an off-ratio tile stays at the origin; a
//! changed copy fails the check. The spec test holds `world_ultra` to every whole game's world. The
//! ignored test builds the real one from the three discs, as build.sh does, and checks it.

use modcheck::json::Json;
use std::path::{Path, PathBuf};
use stitch::build::{Params, build};

fn scratch(name: &str) -> PathBuf {
    let d = Path::new(env!("CARGO_TARGET_TMPDIR")).join("stitch-ultra").join(name);
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

/// A generated track mod `elev_ultra_<name>`: `n + 1` samples a side at `s` ft, gentle hills on `base`, no
/// berm, one rock in the middle.
fn tile(root: &Path, name: &str, n: u32, s: f32, base: f64, surface: u8) -> PathBuf {
    let id = format!("elev_ultra_{name}");
    let dir = root.join(&id);
    std::fs::create_dir_all(&dir).unwrap();
    let w = n + 1;
    let k = f64::from(surface);
    let feet: Vec<f32> = (0..w * w)
        .map(|i| {
            let (x, z) = (f64::from(i % w) * f64::from(s), f64::from(i / w) * f64::from(s));
            (base + 6.0 * (x / (170.0 + 11.0 * k)).sin() * (z / 240.0).cos() + 0.004 * x) as f32
        })
        .collect();
    let (mut g, hs) = trnwrite::Grid::from_feet(w, w, &feet, s).unwrap();
    g.surfaces = vec![surface; (w * w) as usize];
    let trn = trnwrite::build(&g, &trnwrite::Options::new(s, hs)).unwrap();
    let (bytes, _) = trnwrite::write(&trn).unwrap();
    std::fs::write(dir.join(format!("{id}.ps2.trn")), bytes).unwrap();
    let mid = (f64::from(n) * f64::from(s) / 2.0) as f32;
    let mut scene = trnwrite::scene::SceneText::for_terrain(&trn, &id, [mid, base as f32, mid], [0.0, 0.0, 1.0]).to_text();
    scene.push_str(&format!("\r\n[Model1]\r\nSLT=rock\r\nPosition={mid:.2},{base:.2},{mid:.2}\r\n"));
    std::fs::write(dir.join(format!("{id}.scn")), scene).unwrap();
    std::fs::write(
        dir.join("mod.json"),
        format!(
            r#"{{"standard": 1, "kind": "track", "id": "{id}", "name": "Test {name}",
 "source": {{"game": "Real elevation", "data": "generated by stitch's tests", "date": "2026-10-22"}},
 "version": "1.0.0", "author": "stitch tests", "permission": "public-domain",
 "todo": ["generated test map: rock.psg is not in the folder",
          "{id}.scn: TerrainWidthScale and TerrainBreadthScale print the scale in fewer digits than the terrain's"]}}"#
        ),
    )
    .unwrap();
    dir
}

fn world(root: &Path, id: &str, tiles: &[(&str, f32, f64)]) -> PathBuf {
    let mods = root.join("tiles");
    let dirs: Vec<PathBuf> = tiles.iter().enumerate().map(|(i, (n, s, b))| tile(&mods, n, 256, *s, *b, 2 * i as u8 + 1)).collect();
    let mut p = Params::new(id, &format!("Test {id}"));
    p.threads = 4;
    build(&dirs, &root.join("worlds"), &p).unwrap().dir
}

fn meta(dir: &Path) -> Json {
    Json::parse(&std::fs::read_to_string(dir.join("mod.json")).unwrap()).unwrap()
}

fn nums(j: Option<&Json>) -> Vec<f64> {
    j.and_then(Json::arr).unwrap().iter().filter_map(Json::num).collect()
}

/// Two worlds 200 ft apart in height, the second with a 4.499999 ft tile (Untamed's Nat_OR kind), so it
/// can only stay at the origin. The ultra map puts it there and the other past it on a whole leaf, copies
/// both whole, and `stitch check` passes: every tile seam, every point where the new ground meets a world
/// (height and slope across to the quantum), the slopes past every gate, the copies byte for byte.
#[test]
fn two_worlds_join_whole_with_continuous_height_and_slope() {
    let root = scratch("two");
    let a = world(&root, "world_low", &[("a1", 4.5, 100.0), ("a2", 4.5, 115.0)]);
    let b = world(&root, "world_high", &[("b1", 4.5, 300.0), ("b2", 4.499_999, 310.0), ("b3", 4.5, 305.0)]);
    let mut p = Params::new("world_ultra_test", "Test ultra");
    p.threads = 4;
    let built = stitch::ultra::build(&[a.clone(), b.clone()], &root.join("out"), &p).unwrap();
    assert!(built.far_slope <= 0.5, "new ground {} steep", built.far_slope);

    let m = meta(&built.dir);
    let worlds = m.get("stitch").and_then(|s| s.get("worlds")).and_then(Json::arr).unwrap();
    let at = |w: usize| nums(worlds[w].get("at"));
    assert_eq!(at(1), vec![0.0, 0.0], "the world with the off-ratio tile stays at the origin");
    let (ax, az) = (at(0)[0], at(0)[1]);
    // Past it along one axis (the two are square, so a column or a row), on a whole leaf.
    assert!(ax.max(az) > 0.0 && ax.min(az) == 0.0 && (ax / 72.0).fract() == 0.0 && (az / 72.0).fract() == 0.0, "world_low at {ax}, {az}");
    // Every tile moved by its world's offset, keep unchanged; every join of each world there, renamed.
    for (w, dir, pf, off) in [(0, &a, "low_", [ax, az]), (1, &b, "high_", [0.0, 0.0])] {
        let src = meta(dir);
        for t in src.get("tiles").and_then(Json::arr).unwrap() {
            let name = t.get("tile").and_then(Json::str).unwrap();
            let u = m.get("tiles").and_then(Json::arr).unwrap().iter().find(|x| x.get("tile").and_then(Json::str) == Some(name)).unwrap();
            let (sa, ua) = (nums(t.get("at")), nums(u.get("at")));
            assert_eq!(ua, vec![sa[0] + off[0], sa[1] + off[1]], "{name} of world {w}");
            assert_eq!(nums(u.get("keep")), nums(t.get("keep")));
        }
        for j in src.get("joins").and_then(Json::arr).unwrap() {
            let name = format!("{pf}{}", j.get("join").and_then(Json::str).unwrap());
            assert!(m.get("joins").and_then(Json::arr).unwrap().iter().any(|x| x.get("join").and_then(Json::str) == Some(name.as_str())), "{name}");
        }
    }
    assert!(m.get("joins").and_then(Json::arr).unwrap().iter().any(|x| x.get("join").and_then(Json::str).is_some_and(|n| n.starts_with('u'))));
    let todo: Vec<&str> = m.get("todo").and_then(Json::arr).unwrap().iter().filter_map(Json::str).collect();
    assert!(todo.iter().any(|t| t.starts_with("joins/u*")), "{todo:?}");

    let mods = root.join("worlds");
    let r = stitch::check::check(&built.dir, Some(&mods), None);
    assert!(r.ok(), "check failed:\n{}", r.fail.join("\n"));
    assert!(r.world_seam_points > 500, "{} world seam points", r.world_seam_points);
    assert!(r.world_seam_height < 0.05 && r.world_seam_slope < 0.01, "{} ft, {}", r.world_seam_height, r.world_seam_slope);
    assert!(r.note.iter().any(|n| n.starts_with("world_low: ") && n.contains("byte for byte")), "{:?}", r.note);

    // A copied join changed (a new file, so the world's own, which may be the same file, is not) fails.
    let jn = m.get("joins").and_then(Json::arr).unwrap().iter().filter_map(|x| x.get("join").and_then(Json::str)).find(|n| n.starts_with("low_")).unwrap();
    let f = built.dir.join("joins").join(jn).join(format!("{jn}.blend"));
    let mut bytes = std::fs::read(&f).unwrap();
    bytes.reverse();
    std::fs::remove_file(&f).unwrap();
    std::fs::write(&f, bytes).unwrap();
    let r = stitch::check::check(&built.dir, Some(&mods), None);
    assert!(r.fail.iter().any(|x| x.contains(jn) && x.contains("byte for byte")), "{:?}", r.fail);
}

/// A step where the new ground meets a world is caught: the new piece on world_one's x1 edge, rewritten
/// 2 ft higher, fails the world seam check there.
#[test]
fn a_step_at_a_worlds_edge_fails_the_check() {
    let root = scratch("step");
    let a = world(&root, "world_one", &[("c1", 4.5, 150.0), ("c2", 4.5, 160.0)]);
    let b = world(&root, "world_two", &[("d1", 4.5, 170.0), ("d2", 4.5, 155.0)]);
    let mut p = Params::new("world_ultra_step", "Test ultra step");
    p.threads = 4;
    let built = stitch::ultra::build(&[a, b], &root.join("out"), &p).unwrap();
    let m = meta(&built.dir);
    // The new piece that touches world_one's x1 edge, rewritten 2 ft higher.
    let rect = nums(m.get("stitch").and_then(|s| s.get("worlds")).and_then(Json::arr).unwrap()[0].get("rect"));
    let piece = m
        .get("joins")
        .and_then(Json::arr)
        .unwrap()
        .iter()
        .find(|j| j.get("join").and_then(Json::str).is_some_and(|n| n.starts_with('u')) && (nums(j.get("at"))[0] - rect[2]).abs() < 1e-6)
        .unwrap();
    let name = piece.get("join").and_then(Json::str).unwrap();
    let samples = nums(piece.get("samples"));
    let f = built.dir.join("joins").join(name).join(format!("{name}.ps2.trn"));
    let old = std::fs::read(&f).unwrap();
    let t = game_sim::track::Terrain::parse(&old).unwrap();
    let (w, d) = (samples[0] as u32, samples[1] as u32);
    let mut feet = Vec::new();
    for z in 0..d {
        for x in 0..w {
            let (cx, cz) = (x.min(w - 2), z.min(d - 2));
            let q = t.cell(cx, cz, 1).unwrap();
            feet.push((t.scale * q.height[((x - cx) + 2 * (z - cz)) as usize]).0 + 2.0);
        }
    }
    let (g, hs) = trnwrite::Grid::from_feet(w, d, &feet, 4.5).unwrap();
    let (bytes, _) = trnwrite::write(&trnwrite::build(&g, &trnwrite::Options::new(4.5, hs)).unwrap()).unwrap();
    std::fs::remove_file(&f).unwrap();
    std::fs::write(&f, bytes).unwrap();
    let r = stitch::check::check(&built.dir, None, None);
    assert!(r.fail.iter().any(|x| x.starts_with("world_one edge 2") && x.contains(name)), "{:?}", &r.fail[..r.fail.len().min(5)]);
}

/// `world_ultra.json` joins every whole game's world: every other spec of tiles, except one whose tiles
/// are all in another spec (world_mxu_free, the five freerides of world_mxu). So a new game's giant map
/// (M3's, M11's) fails this until it is added, and C5 is re-run with it.
#[test]
fn the_spec_joins_every_games_world() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("worlds");
    let mut specs: Vec<Json> = std::fs::read_dir(&dir)
        .unwrap()
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|e| e == "json"))
        .map(|p| Json::parse(&std::fs::read_to_string(p).unwrap()).unwrap())
        .collect();
    specs.sort_by_key(|j| j.get("id").and_then(Json::str).unwrap().to_owned());
    let strs = |j: &Json, k: &str| -> Vec<String> { j.get(k).and_then(Json::arr).unwrap_or_default().iter().filter_map(Json::str).map(str::to_owned).collect() };
    let ultra = specs.iter().find(|j| j.get("id").and_then(Json::str) == Some("world_ultra")).expect("worlds/world_ultra.json");
    let tiled: Vec<&Json> = specs.iter().filter(|j| j.get("tiles").is_some()).collect();
    let whole: Vec<String> = tiled
        .iter()
        .filter(|j| {
            let mine = strs(j, "tiles");
            !tiled.iter().any(|o| o.get("id") != j.get("id") && strs(o, "tiles").len() > mine.len() && mine.iter().all(|t| strs(o, "tiles").contains(t)))
        })
        .map(|j| j.get("id").and_then(Json::str).unwrap().to_owned())
        .collect();
    let mut got = strs(ultra, "worlds");
    got.sort();
    assert_eq!(got, whole, "world_ultra's worlds are not every game's whole world");
    // MX Unleashed's first: its sky and spawn are the ultra map's.
    assert_eq!(strs(ultra, "worlds")[0], "world_mxu");
    assert_eq!(ultra.get("sky").and_then(Json::str), Some("mxu_free06"));
    for k in ["max_slope", "min_gap", "fade", "chunk", "todo"] {
        assert!(ultra.get(k).is_none(), "the spec sets {k}");
    }
}

// ---- against the user's discs (`cargo test --release -p stitch --test world_ultra -- --ignored`) ----

/// The real ultra map, built as build.sh builds it: every MX vs. ATV Unleashed and Untamed map imported,
/// then `stitch --mods --out` (which imports MX Unleashed's tiles itself and builds every spec, the
/// ultra map last), then `stitch check` with the discs.
#[test]
#[ignore = "needs the MX Unleashed, MX vs. ATV Unleashed and Untamed discs in iso/ or $DISCX_ISO; about 9 minutes in release, 5 GB"]
fn the_ultra_map_of_every_game_builds_and_checks() {
    use import_mxvatv::untamed;
    let iso = std::env::var_os("DISCX_ISO").map(PathBuf::from).unwrap_or_else(|| Path::new(env!("CARGO_MANIFEST_DIR")).join("../../iso"));
    let images = discx::images(&iso).unwrap();
    let disc = |boot: &str| {
        let (image, _) = images.iter().find(|(_, b)| b.as_deref().is_some_and(|b| b.eq_ignore_ascii_case(boot))).unwrap_or_else(|| panic!("no {boot} disc in {}", iso.display()));
        discx::Disc::open(image).unwrap()
    };
    let root = Path::new(env!("CARGO_TARGET_TMPDIR")).join("stitch-world-ultra");
    let _ = std::fs::remove_dir_all(&root);
    let tracks = root.join("mods").join("tracks");
    let mut d = disc("SLUS_211.04");
    for f in import_mxvatv::map_folders(&d) {
        import_mxvatv::import(&import_mxvatv::load_map(&mut d, &f).unwrap(), &tracks).unwrap();
    }
    let mut d = disc(untamed::BOOT);
    let master = untamed::master(&mut d).unwrap();
    for (f, pick) in untamed::chosen(&d, &master.1) {
        if pick.is_ok() {
            import_mxvatv::import(&untamed::load_map(&mut d, &f, &master).unwrap(), &tracks).unwrap();
        }
    }
    let stage = root.join("stage");
    let out = std::process::Command::new(env!("CARGO_BIN_EXE_stitch"))
        .arg("--mods")
        .arg(root.join("mods"))
        .arg("--out")
        .arg(&stage)
        .env("DISCX_ISO", &iso)
        .output()
        .unwrap();
    let said = String::from_utf8_lossy(&out.stdout);
    assert!(out.status.success(), "{said}\n{}", String::from_utf8_lossy(&out.stderr));
    assert!(said.contains("world_ultra (3 worlds, 77 tiles"), "{said}");
    let r = stitch::check::check(&stage.join("world_ultra"), Some(&stage), Some(iso));
    assert!(r.ok(), "check failed:\n{}", r.fail.join("\n"));
    assert!(r.world_seam_points > 40_000, "{} world seam points", r.world_seam_points);
    assert!(r.seam_points > 700_000, "{} seam points", r.seam_points);
}
