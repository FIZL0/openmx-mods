/// A spec's build parameters, as `stitch --mods --out` reads them.
fn params(j: &modcheck::json::Json) -> Params {
    use modcheck::json::Json;
    let g = |k: &str| j.get(k).and_then(Json::str).map(str::to_owned);
    let mut p = Params::new(&g("id").unwrap(), &g("name").unwrap());
    p.sky = g("sky");
    p.todo = j.get("todo").and_then(Json::arr).unwrap_or_default().iter().filter_map(Json::str).map(str::to_owned).collect();
    for (k, v) in [("max_slope", &mut p.max_slope), ("min_gap", &mut p.min_gap), ("fade", &mut p.fade)] {
        if let Some(n) = j.get(k).and_then(Json::num) {
            *v = n;
        }
    }
    if let Some(v) = j.get("chunk").and_then(Json::num) {
        p.chunk = v as u32;
    }
    p
}

fn spec(id: &str) -> modcheck::json::Json {
    let p = Path::new(env!("CARGO_MANIFEST_DIR")).join("worlds").join(format!("{id}.json"));
    modcheck::json::Json::parse(&std::fs::read_to_string(p).unwrap()).unwrap()
}

/// Every map of the three discs imported into `<root>/tracks` (once: a second run with
/// `C11_ROOT` set reuses them).
fn imported(root: &Path, iso: &Path) -> PathBuf {
    use import_mxvatv::{mxu, untamed};
    let tracks = root.join("tracks");
    if tracks.join("mxu_nat01").join("mod.json").exists() && tracks.join("untamed_nat_or").join("mod.json").exists() {
        return tracks;
    }
    let images = discx::images(iso).unwrap();
    let disc = |boot: &str| {
        let (image, _) = images.iter().find(|(_, b)| b.as_deref().is_some_and(|b| b.eq_ignore_ascii_case(boot))).unwrap_or_else(|| panic!("no {boot} disc in {}", iso.display()));
        discx::Disc::open(image).unwrap()
    };
    let mut d = disc("SLUS_211.04");
    for f in import_mxvatv::map_folders(&d) {
        import_mxvatv::import(&import_mxvatv::load_map(&mut d, &f).unwrap(), &tracks).unwrap();
    }
    let mut d = disc(untamed::BOOT);
    let master = untamed::master(&mut d).unwrap();
    for (f, pick) in untamed::chosen(&d, &master.1) {
        if pick.is_ok() {
            import_mxvatv::import(&untamed::load_map(&mut d, &f, &master).unwrap(), &tracks).unwrap();
        }
    }
    // MX Unleashed's: the ones world_mxu names, as `stitch --mods --out` imports them.
    let want: Vec<String> = spec("world_mxu").get("tiles").and_then(modcheck::json::Json::arr).unwrap().iter().filter_map(modcheck::json::Json::str).map(|t| t["mxu_".len()..].to_owned()).collect();
    let mut d = disc(mxu::BOOT);
    for t in mxu::tracks(&d) {
        if want.iter().any(|w| w.eq_ignore_ascii_case(&t)) {
            import_mxvatv::import(&mxu::load_map(&mut d, &t).unwrap(), &tracks).unwrap();
        }
    }
    tracks
}

/// One world's summary as a line for the notes.
fn line(id: &str, w: &openmx::World, s: &Summary, strips: (usize, usize, Vec<String>)) -> String {
    format!(
        "{id}: {} tiles, {} joins, {:.1} x {:.1} ft; tiles {} points ({} differ), joins {} points ({} differ), {} join samples against stitch's field ({} past the quantum, worst {:.4} ft over); rounding into a piece's own feet at most {} ft; {} of {} edge points own nothing{}",
        w.tile_count,
        w.pieces.len() - w.tile_count,
        s.width,
        s.depth,
        s.tiles.points,
        s.tiles.differ,
        s.joins.points,
        s.joins.differ,
        s.joins.field_points,
        s.joins.field_over,
        s.joins.field_worst,
        s.tiles.rounding.max(s.joins.rounding),
        strips.1,
        strips.0,
        if strips.2.is_empty() { String::new() } else { format!(" ({})", strips.2.join("; ")) }
    )
}

/// **C11 on the real maps.** world_mxu, world_mxvatv and world_untamed built from their specs (stitch's
/// `build`, so its field is at hand), and world_ultra from those three: each loaded as openmx loads it,
/// every tile's ground the imported map's own to the bit (24 × 24 points and its four edges), every
/// join's its file's and, at every 8th sample, stitch's to the quantum, and no ground left to no one
/// between any two pieces. Writes the lines to `<root>/report.txt`.
#[test]
#[ignore = "needs the MX Unleashed, MX vs. ATV Unleashed and Untamed discs in iso/ or $DISCX_ISO; about 10 minutes in release, 6 GB"]
fn every_world_of_the_three_discs_in_openmx() {
    let iso = std::env::var_os("DISCX_ISO").map(PathBuf::from).unwrap_or_else(|| Path::new(env!("CARGO_MANIFEST_DIR")).join("../../iso"));
    let root = std::env::var_os("C11_ROOT").map(PathBuf::from).unwrap_or_else(|| Path::new(env!("CARGO_TARGET_TMPDIR")).join("stitch-openmx-real"));
    let tracks = imported(&root, &iso);
    let out = root.join("out");
    let threads = std::thread::available_parallelism().map_or(4, |n| n.get());
    let mut report = Vec::new();
    let mut worlds = Vec::new();
    for id in ["world_mxu", "world_mxvatv", "world_untamed"] {
        let j = spec(id);
        let p = params(&j);
        let names: Vec<String> = j.get("tiles").and_then(modcheck::json::Json::arr).unwrap().iter().filter_map(modcheck::json::Json::str).map(str::to_owned).collect();
        let dirs: Vec<PathBuf> = names.iter().map(|t| tracks.join(t)).collect();
        let built = build(&dirs, &out, &p).unwrap();
        let tiles: Vec<stitch::Tile> = dirs.iter().map(|d| stitch::Tile::load(d).unwrap()).collect();
        let terrains: Vec<_> = tiles.iter().map(stitch::Tile::terrain).collect();
        let plan = &built.plan;
        let field = |x: f64, z: f64| plan.at(&tiles, &terrains, &plan.candidates([x, z, x, z]), x, z).h;
        let w = openmx::load(&built.dir).unwrap();
        let s = openmx::check_world(&w, &|t: &str| tracks.join(t), Some(&field), 24, 8, threads).unwrap();
        let st = openmx::strips(&w, &w.tiled().unwrap(), 2.0);
        let l = line(id, &w, &s, st.clone());
        println!("{l}");
        report.push(l);
        assert_clean(id, &s, true);
        assert_eq!(st.1, 0, "{id}: {:?}", st.2);
        worlds.push(built.dir);
    }
    let j = spec("world_ultra");
    let p = params(&j);
    let u = stitch::ultra::build(&worlds, &out, &p).unwrap();
    let w = openmx::load(&u.dir).unwrap();
    let s = openmx::check_world(&w, &|t: &str| tracks.join(t), None, 24, 8, threads).unwrap();
    let st = openmx::strips(&w, &w.tiled().unwrap(), 2.0);
    let l = line("world_ultra", &w, &s, st.clone());
    println!("{l}");
    report.push(l);
    assert_clean("world_ultra", &s, false);
    assert_eq!(st.1, 0, "world_ultra: {:?}", st.2);
    worlds.push(u.dir);
    match openmx_bin() {
        Some(bin) => report.extend(rides(&bin, &root, &worlds)),
        None => report.push("rides: skipped, no openmx binary ($OPENMX_BIN, extracted/openmx-target, openmx/target)".into()),
    }
    std::fs::write(root.join("report.txt"), report.join("\n") + "\n").unwrap();
    for l in &report {
        assert!(!l.contains("FAIL"), "{l}");
    }
}

/// openmx on the built worlds (`dirs`: world_mxu, world_mxvatv, world_untamed, world_ultra): a ride
/// on the gas across every join between two neighbouring tiles of each game's world and across every
/// gap between two worlds in the ultra map, none thrown back before the world's outer edge; the same
/// ride on world_untamed alone and in the ultra map (the same coordinates) tick for tick the same, and
/// on world_mxu alone and 76,032 ft out in the ultra map, how far apart; and the ultra map's far corner
/// ridden. Lines for the report, `FAIL` in a line that fails.
fn rides(bin: &Path, root: &Path, dirs: &[PathBuf]) -> Vec<String> {
    let mods = root.join("run");
    let _ = std::fs::remove_dir_all(&mods);
    std::fs::create_dir_all(mods.join("tracks")).unwrap();
    for d in dirs {
        std::os::unix::fs::symlink(d, mods.join("tracks").join(d.file_name().unwrap())).unwrap();
    }
    let mut lines = Vec::new();
    let threads = std::thread::available_parallelism().map_or(4, |n| n.get()).min(12);
    let ultra = openmx::load(&dirs[3]).unwrap();
    for d in dirs {
        let w = openmx::load(d).unwrap();
        let tiled = w.tiled().unwrap();
        let all = neighbours(&w);
        // The ultra map's own rides are the ones between two worlds; within a world they are the world's.
        let game = |i: usize| w.pieces[i].tile.name.split('_').next().unwrap_or("").to_owned();
        let pairs: Vec<_> = all.into_iter().filter(|p| w.id != "world_ultra" || game(p.0) != game(p.1)).collect();
        let next = std::sync::atomic::AtomicUsize::new(0);
        let done = std::sync::Mutex::new(Vec::new());
        std::thread::scope(|sc| {
            for _ in 0..threads {
                sc.spawn(|| loop {
                    let k = next.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
                    let Some(&(a, b, start, deg, dist)) = pairs.get(k) else { break };
                    let frames = ((dist / 3.0) as u32 + 120).min(3000);
                    let t = ride(bin, &mods, &w.id, start, deg, frames, true);
                    done.lock().unwrap().push((k, a, b, t));
                });
            }
        });
        let mut done = done.into_inner().unwrap();
        done.sort_by_key(|d| d.0);
        let (mut reached, mut thrown, mut wrecked, mut above) = (0, 0, 0, 0.0f32);
        for (_, a, b, t) in &done {
            let (r, throws, wrecks, owners, high) = crossing(&w, &tiled, t, *b);
            let (na, nb) = (&w.pieces[*a].tile.name, &w.pieces[*b].tile.name);
            reached += usize::from(r);
            wrecked += usize::from(wrecks > 0);
            above = above.max(high);
            if !throws.is_empty() {
                thrown += 1;
                lines.push(format!("FAIL {}: {na} -> {nb} thrown back inside the world: {} (crossed {})", w.id, throws.join("; "), owners.join(" > ")));
            } else if !r {
                lines.push(format!("{}: {na} -> {nb} did not reach {nb} ({wrecks} wrecks; crossed {})", w.id, owners.join(" > ")));
            }
        }
        lines.push(format!(
            "{}: {} rides across a join on the gas: {reached} reached the far tile, {thrown} thrown back, {wrecked} wrecked on the way; on the ground at most {above:.2} ft from Tiled::at under the bike",
            w.id,
            done.len()
        ));
    }
    lines.extend(far(bin, &mods, dirs, &ultra));
    lines
}

/// The far-from-origin rides: world_untamed sits at the ultra map's origin and must ride the same;
/// world_mxu sits 76,032 ft out; the ultra map's far corner.
fn far(bin: &Path, mods: &Path, dirs: &[PathBuf], ultra: &openmx::World) -> Vec<String> {
    let mut lines = Vec::new();
    for (k, id) in [(2usize, "world_untamed"), (0, "world_mxu")] {
        let w = openmx::load(&dirs[k]).unwrap();
        let Some(&(a, _, start, deg, _)) = neighbours(&w).first() else { continue };
        let name = &w.pieces[a].tile.name;
        let off = [0, 1].map(|i| ultra.pieces[ultra.index(name).unwrap()].tile.at[i].0 - w.pieces[a].tile.at[i].0);
        let alone = ride(bin, mods, id, start, deg, 400, true);
        let moved = ride(bin, mods, "world_ultra", [start[0] + off[0], start[1] + off[1]], deg, 400, true);
        let apart: Vec<f32> = alone.iter().zip(&moved).map(|(a, m)| (a.x + off[0] - m.x).abs().max((a.y - m.y).abs()).max((a.z + off[1] - m.z).abs())).collect();
        let first = apart.iter().position(|d| *d > 0.0);
        let worst = apart.iter().copied().fold(0.0f32, f32::max);
        let at100 = apart.get(100).copied().unwrap_or(f32::NAN);
        let same = off == [0.0, 0.0];
        let verdict = if same && first.is_some() { "FAIL " } else { "" };
        lines.push(format!(
            "{verdict}{id} at ({}, {}) in world_ultra: from {name} ({:.0}, {:.0}) on the gas 400 ticks, alone and in the ultra map first apart on tick {first:?}, {at100:.4} ft apart at tick 100, at most {worst:.4} ft",
            off[0], off[1], start[0], start[1]
        ));
    }
    // Far out: world_mxu's farthest tile's start line and world_mxu's far corner, ridden standing and on
    // the gas alone and where the ultra map puts them, the same spot in each's own feet.
    let w = openmx::load(&dirs[0]).unwrap();
    let ta = w.tiled().unwrap();
    let far_tile = (0..w.tile_count).max_by(|a, b| (w.pieces[*a].tile.at[0].0 + w.pieces[*a].tile.at[1].0).total_cmp(&(w.pieces[*b].tile.at[0].0 + w.pieces[*b].tile.at[1].0))).unwrap();
    let name = w.pieces[far_tile].tile.name.clone();
    let spawn = stitch::Tile::load(&w.pieces[far_tile].dir).unwrap().spawn();
    let start = [w.pieces[far_tile].tile.at[0].0 + spawn[0] as f32, w.pieces[far_tile].tile.at[1].0 + spawn[2] as f32];
    let off = [0, 1].map(|i| ultra.pieces[ultra.index(&name).unwrap()].tile.at[i].0 - w.pieces[far_tile].tile.at[i].0);
    let spots = [
        (format!("{name}'s start"), start, 45.0f32),
        ("world_mxu's far corner".to_string(), [ta.area.width.0 - 400.0, ta.area.depth.0 - 400.0], 225.0),
    ];
    // How a ride moves: the largest spread and tick-to-tick step on the brakes (ticks 200-300), and the
    // largest second difference of the position on the gas past tick 60 (how unevenly it moves).
    let still = |t: &[Tick]| {
        let tail = &t[200.min(t.len())..];
        if tail.iter().any(|k| k.wreck) {
            return (f32::NAN, f32::NAN);
        }
        let spread = |f: fn(&Tick) -> f32| tail.iter().map(f).fold(f32::MIN, f32::max) - tail.iter().map(f).fold(f32::MAX, f32::min);
        let step = tail.windows(2).map(|p| (p[1].x - p[0].x).abs().max((p[1].z - p[0].z).abs()).max((p[1].y - p[0].y).abs())).fold(0.0f32, f32::max);
        (spread(|k| k.x).max(spread(|k| k.z)).max(spread(|k| k.y)), step)
    };
    let jerk = |t: &[Tick]| t.windows(3).skip(60).filter(|p| p.iter().all(|k| !k.wreck)).map(|p| ((p[2].x - 2.0 * p[1].x + p[0].x).powi(2) + (p[2].y - 2.0 * p[1].y + p[0].y).powi(2) + (p[2].z - 2.0 * p[1].z + p[0].z).powi(2)).sqrt()).fold(0.0f32, f32::max);
    // The same on the brakes near the origin, on world_untamed's untamed_nat_or start, for scale.
    let u = openmx::load(&dirs[2]).unwrap();
    if let Some(i) = u.index("untamed_nat_or") {
        let sp = stitch::Tile::load(&u.pieces[i].dir).unwrap().spawn();
        let at = [u.pieces[i].tile.at[0].0 + sp[0] as f32, u.pieces[i].tile.at[1].0 + sp[2] as f32];
        let (spread, step) = still(&ride(bin, mods, "world_ultra", at, 45.0, 300, false));
        lines.push(format!("untamed_nat_or's start at ({:.0}, {:.0}) in world_ultra: on the brakes, spread {spread:.4} ft, largest step {step:.4} ft (for scale)", at[0], at[1]));
    }
    for (label, at, deg) in spots {
        let moved = [at[0] + off[0], at[1] + off[1]];
        let (sa, su) = (ride(bin, mods, "world_mxu", at, deg, 300, false), ride(bin, mods, "world_ultra", moved, deg, 300, false));
        let (ga, gu) = (ride(bin, mods, "world_mxu", at, deg, 300, true), ride(bin, mods, "world_ultra", moved, deg, 300, true));
        let ((spa, sta), (spu, stu)) = (still(&sa), still(&su));
        let (ja, ju) = (jerk(&ga), jerk(&gu));
        let bad = su.iter().chain(&gu).any(|k| !k.x.is_finite() || !k.y.is_finite() || !k.z.is_finite());
        let thrown = gu.iter().any(|k| k.wreck && k.speed > THROW_SPEED);
        // Far from the origin a float holds 1/128 ft; what is jitter is a ride that moves less evenly
        // than the same ride alone by more than a few of those.
        let fail = bad || thrown || ju > ja + 0.05 || stu > sta + 0.05 || spa.is_nan() != spu.is_nan();
        lines.push(format!(
            "{}{label} at ({:.0}, {:.0}) in world_ultra: on the brakes, spread {spa:.4} ft alone and {spu:.4} in the ultra map, largest step {sta:.4} and {stu:.4}; on the gas, largest second difference past tick 60 {ja:.4} and {ju:.4} ft{}",
            if fail { "FAIL " } else { "" },
            moved[0],
            moved[1],
            if thrown { ", thrown back" } else { "" }
        ));
    }
    lines
}

