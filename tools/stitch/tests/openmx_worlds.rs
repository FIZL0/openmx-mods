/// One traced tick of `--trace-feel`.
#[derive(Clone, Debug)]
struct Tick {
    speed: f32,
    x: f32,
    y: f32,
    z: f32,
    ground: bool,
    wreck: bool,
}

/// A thrown rider: the edge test's throw, which leaves at about 300 ft/s.
const THROW_SPEED: f32 = 250.0;

/// Run openmx headless on world `id` in `mods` (a folder with `tracks/<id>`), from its working folder
/// (`openmx/`, where kit.toml finds the disc). Returns everything it said.
fn openmx_run(bin: &Path, mods: &Path, id: &str, args: &[String]) -> String {
    let cwd = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../openmx");
    let out = std::process::Command::new(bin)
        .current_dir(&cwd)
        .args(["--headless", "--no-sound", "--track", id, "--mods"])
        .arg(mods)
        .args(args)
        .output()
        .expect("openmx runs");
    let said = format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr));
    assert!(out.status.success(), "openmx {args:?} failed:\n{said}");
    said
}

/// From `(x, z)` facing `degrees` (0 along +z, 90 along +x) for `frames` ticks, on the gas or on the
/// brakes.
fn ride(bin: &Path, mods: &Path, id: &str, at: [f32; 2], degrees: f32, frames: u32, gas: bool) -> Vec<Tick> {
    let mut args: Vec<String> = ["--trace", &frames.to_string(), "--trace-feel", "--trace-at", &format!("{},{},{degrees}", at[0], at[1])].map(String::from).into();
    args.push(if gas { "--trace-gas" } else { "--trace-brake" }.into());
    let said = openmx_run(bin, mods, id, &args);
    let rows: Vec<Tick> = said
        .lines()
        .filter_map(|l| {
            let w: Vec<&str> = l.split_whitespace().collect();
            (w.len() == 12 && w[0].parse::<u32>().is_ok()).then(|| {
                let f = |i: usize| w[i].parse::<f32>().unwrap_or(f32::NAN);
                Tick { speed: f(1), x: f(5), y: f(6), z: f(7), ground: w[10] == "1", wreck: w[11] == "1" }
            })
        })
        .collect();
    assert!(!rows.is_empty(), "no trace rows:\n{said}");
    rows
}

/// A tile's owned rectangle in world feet.
fn owned(t: &game_sim::tiles::Tile) -> [f32; 4] {
    let [x0, z0, x1, z1] = t.keep.map(|k| k as f32 * t.spacing.0);
    [t.at[0].0 + x0, t.at[1].0 + z0, t.at[0].0 + x1, t.at[1].0 + z1]
}

/// Neighbouring tiles across a join: `b` past `a` along +x (or +z), their rectangles overlapping by
/// 600 ft or more across, and no other tile's rectangle in the corridor between them. Each as
/// `(a, b, start, degrees, distance)`, starting 150 ft inside `a`'s edge in the middle of the overlap.
fn neighbours(w: &openmx::World) -> Vec<(usize, usize, [f32; 2], f32, f32)> {
    let r: Vec<[f32; 4]> = (0..w.tile_count).map(|i| owned(&w.pieces[i].tile)).collect();
    let mut out = Vec::new();
    for a in 0..r.len() {
        for b in 0..r.len() {
            for axis in 0..2 {
                let (lo, hi) = (r[a][1 - axis].max(r[b][1 - axis]), r[a][3 - axis].min(r[b][3 - axis]));
                let gap = r[b][axis] - r[a][axis + 2];
                if a == b || hi - lo < 600.0 || gap <= 0.0 {
                    continue;
                }
                let corridor = |c: &[f32; 4]| c[axis] < r[b][axis] && c[axis + 2] > r[a][axis + 2] && c[1 - axis] < hi && c[3 - axis] > lo;
                if (0..r.len()).any(|c| c != a && c != b && corridor(&r[c])) {
                    continue;
                }
                let mid = (lo + hi) / 2.0;
                let edge = r[a][axis + 2] - 150.0;
                let start = if axis == 0 { [edge, mid] } else { [mid, edge] };
                out.push((a, b, start, if axis == 0 { 90.0 } else { 0.0 }, gap + 300.0));
            }
        }
    }
    out
}

/// What a ride across a join came to: whether it reached `b`, the throws and other wrecks on the
/// way, the owners it crossed, and the largest height above the ground under it while on the ground.
fn crossing(w: &openmx::World, tiled: &game_sim::tiles::Tiled, ticks: &[Tick], b: usize) -> (bool, Vec<String>, usize, Vec<String>, f32) {
    let (mut reached, mut throws, mut wrecks, mut owners, mut above) = (false, Vec::new(), 0, Vec::<String>::new(), 0.0f32);
    for (k, t) in ticks.iter().enumerate() {
        let own = tiled.owner(ps2_float::F(t.x), ps2_float::F(t.z)).map(|o| o.0);
        if own == Some(b) {
            reached = true;
        }
        let name = own.map_or("none".to_string(), |o| w.pieces[o].tile.name.clone());
        if owners.last() != Some(&name) {
            owners.push(name.clone());
        }
        if t.wreck && (k == 0 || !ticks[k - 1].wreck) {
            if t.speed > THROW_SPEED {
                throws.push(format!("tick {k} at ({:.1}, {:.1}) on {name}", t.x, t.z));
            } else {
                wrecks += 1;
            }
        }
        if t.ground && !t.wreck {
            if let Some(h) = tiled.at(ps2_float::F(t.x), ps2_float::F(t.z)) {
                above = above.max((t.y - h.y.0).abs());
            }
        }
        if !throws.is_empty() || reached && k > 0 && own != Some(b) {
            break;
        }
    }
    (reached, throws, wrecks, owners, above)
}

/// **The look at every C9 gate, for the eye** (MD9). For each world built by
/// [`every_world_of_the_three_discs_in_openmx`] (in `$C11_ROOT/out`), every tile edge whose seam gate
/// (`stitch.gates`, C9) is past C1's: a pair of `--shot-pose` shots under the Global sky, one 60 ft
/// inside the tile looking out across its edge, one at the gate in the join looking back, both 12 ft
/// over the ground. Written to `$C11_ROOT/shots/<world>/<tile>_<edge>_{in,out}.png`, with each world's
/// pairs side by side in `<world>.png` sheets when ImageMagick's `montage` is there. Nothing is asserted
/// past openmx writing every picture: a seam in look is read off them by eye.
#[test]
#[ignore = "needs the worlds every_world_of_the_three_discs_in_openmx built, the discs and an openmx binary; about 5 minutes"]
fn shots_at_every_gate() {
    use modcheck::json::Json;
    let root = std::env::var_os("C11_ROOT").map(PathBuf::from).unwrap_or_else(|| Path::new(env!("CARGO_TARGET_TMPDIR")).join("stitch-openmx-real"));
    let bin = openmx_bin().expect("an openmx binary");
    let mods = root.join("run");
    assert!(mods.join("tracks/world_ultra/mod.json").exists(), "run every_world_of_the_three_discs_in_openmx first");
    let threads = std::thread::available_parallelism().map_or(4, |n| n.get()).min(6);
    for id in ["world_mxu", "world_mxvatv", "world_untamed", "world_ultra"] {
        let dir = mods.join("tracks").join(id);
        let meta = Json::parse(&std::fs::read_to_string(dir.join("mod.json")).unwrap()).unwrap();
        let st = meta.get("stitch").unwrap();
        let (step, fade) = (st.get("spacing").and_then(Json::num).unwrap(), st.get("fade").and_then(Json::num).unwrap());
        let base = 2.0 * step + 3.0 * fade;
        let w = openmx::load(&dir).unwrap();
        let tiled = w.tiled().unwrap();
        let ground = |x: f32, z: f32| tiled.at(ps2_float::F(x), ps2_float::F(z)).map_or(f32::NAN, |h| h.y.0);
        let out = root.join("shots").join(id);
        let _ = std::fs::remove_dir_all(&out);
        std::fs::create_dir_all(&out).unwrap();
        let mut jobs = Vec::new();
        for g in st.get("gates").and_then(Json::arr).unwrap_or_default() {
            let tile = g.get("tile").and_then(Json::str).unwrap();
            let edges: Vec<f64> = g.get("edges").and_then(Json::arr).unwrap().iter().filter_map(Json::num).collect();
            let Some(i) = w.index(tile) else { continue };
            let r = owned(&w.pieces[i].tile);
            for (e, gate) in edges.iter().enumerate() {
                if *gate <= base + 1e-6 {
                    continue;
                }
                // Edge e: 0 x0, 1 z0, 2 x1, 3 z1. Outward along it, and the edge's middle.
                let (out_dir, mid) = match e {
                    0 => ([-1.0f32, 0.0], [r[0], (r[1] + r[3]) / 2.0]),
                    1 => ([0.0, -1.0], [(r[0] + r[2]) / 2.0, r[1]]),
                    2 => ([1.0, 0.0], [r[2], (r[1] + r[3]) / 2.0]),
                    _ => ([0.0, 1.0], [(r[0] + r[2]) / 2.0, r[3]]),
                };
                let yaw_out = out_dir[0].atan2(out_dir[1]).to_degrees();
                let inside = [mid[0] - 60.0 * out_dir[0], mid[1] - 60.0 * out_dir[1]];
                // At the gate, or nearer where the gate runs off the world (mxu_nat17's 2,808 ft).
                let mut d = *gate as f32;
                while d > 20.0 && ground(mid[0] + d * out_dir[0], mid[1] + d * out_dir[1]).is_nan() {
                    d -= 20.0;
                }
                let outside = [mid[0] + d * out_dir[0], mid[1] + d * out_dir[1]];
                let name = format!("{tile}_{}", ["x0", "z0", "x1", "z1"][e]);
                jobs.push((format!("{name}_in"), inside, yaw_out));
                jobs.push((format!("{name}_out"), outside, yaw_out + 180.0));
            }
        }
        // The rider stands under the eye (`--trace-at`): openmx streams the ground in round the rider
        // (MD17), and from the world's spawn the ground under a far pose is not drawn.
        let jobs: Vec<(String, String, String)> = jobs
            .into_iter()
            .map(|(name, at, yaw)| (name, format!("{},{},{},{yaw},-8,85", at[0], ground(at[0], at[1]) + 12.0, at[1]), format!("{},{},{yaw}", at[0], at[1])))
            .collect();
        let next = std::sync::atomic::AtomicUsize::new(0);
        std::thread::scope(|sc| {
            for _ in 0..threads {
                sc.spawn(|| loop {
                    let k = next.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
                    let Some((name, pose, rider)) = jobs.get(k) else { break };
                    let png = out.join(format!("{name}.png"));
                    let args: Vec<String> =
                        ["--shot", png.to_str().unwrap(), "--shot-pose", pose, "--trace-at", rider, "--frames", "3", "--world-sky", "global", "--overlay", "none", "--minimap", "off"].map(String::from).into();
                    openmx_run(&bin, &mods, id, &args);
                    assert!(png.is_file(), "{id}: no {name}.png");
                });
            }
        });
        std::fs::write(out.join("poses.txt"), jobs.iter().map(|(n, p, r)| format!("{n}: --shot-pose {p} --trace-at {r}\n")).collect::<String>()).unwrap();
        let mut names: Vec<String> = jobs.iter().map(|j| j.0.clone()).collect();
        names.sort();
        let files: Vec<PathBuf> = names.iter().map(|n| out.join(format!("{n}.png"))).collect();
        let sheet = root.join("shots").join(format!("{id}.png"));
        let made = std::process::Command::new("montage")
            .args(["-label", "%t", "-pointsize", "10"])
            .args(&files)
            .args(["-tile", "4x", "-geometry", "320x224+2+2"])
            .arg(&sheet)
            .status()
            .map(|s| s.success())
            .unwrap_or(false);
        println!("{id}: {} shots at {} gates{}", jobs.len(), jobs.len() / 2, if made { format!(", sheet {}", sheet.display()) } else { String::new() });
    }
}

