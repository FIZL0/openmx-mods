//! openmx MD54: a wrapped world's join across the wrap is as wide as its stitched joins.
//!
//! The layout's first line starts in from the lattice's origin by `pad` at least, more where a tile is
//! cut deep (Dallas's ridge cut puts world_mxu_free's first column 792 ft in); that band before the first
//! line is half of each join across the wrap, so on a wrapped axis no pad is left past the last line as
//! well. Before, world_mxu_free's Norfolk→Dallas join over the x seam was 1134 ft against 135 ft for
//! every stitched join. Generated 2×2 world, four heights 30 ft apart, so the pairs across the wrap
//! face the same height steps as the pairs within it.

use std::path::{Path, PathBuf};
use stitch::build::{Params, build, gap_for};

fn scratch(name: &str) -> PathBuf {
    let d = Path::new(env!("CARGO_TARGET_TMPDIR")).join("stitch-wrap-width").join(name);
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

/// A generated track mod `elev_md54_<name>`: `n + 1` samples a side at 4.5 ft, hills on `base`.
fn tile(root: &Path, name: &str, n: u32, base: f64) -> PathBuf {
    let id = format!("elev_md54_{name}");
    let dir = root.join(&id);
    std::fs::create_dir_all(&dir).unwrap();
    let (w, s) = (n + 1, 4.5f32);
    let feet: Vec<f32> = (0..w * w)
        .map(|i| {
            let (x, z) = (f64::from(i % w) * f64::from(s), f64::from(i / w) * f64::from(s));
            (base + 8.0 * (x / 190.0).sin() * (z / 230.0).cos() + 0.005 * z) as f32
        })
        .collect();
    let (mut g, hs) = trnwrite::Grid::from_feet(w, w, &feet, s).unwrap();
    g.surfaces = vec![1; (w * w) as usize];
    let trn = trnwrite::build(&g, &trnwrite::Options::new(s, hs)).unwrap();
    let (bytes, _) = trnwrite::write(&trn).unwrap();
    std::fs::write(dir.join(format!("{id}.ps2.trn")), bytes).unwrap();
    let mid = (f64::from(n) * f64::from(s) / 2.0) as f32;
    let scene = trnwrite::scene::SceneText::for_terrain(&trn, &id, [mid, base as f32, mid], [0.0, 0.0, 1.0]).to_text();
    std::fs::write(dir.join(format!("{id}.scn")), scene).unwrap();
    std::fs::write(
        dir.join("mod.json"),
        format!(
            r#"{{"standard": 1, "kind": "track", "id": "{id}", "name": "Test {name}",
 "source": {{"game": "Real elevation", "data": "generated by stitch's tests", "date": "2026-10-27"}},
 "version": "1.0.0", "author": "stitch tests", "permission": "public-domain",
 "todo": ["generated test map",
          "{id}.scn: TerrainWidthScale and TerrainBreadthScale print the scale in fewer digits than the terrain's"]}}"#
        ),
    )
    .unwrap();
    dir
}

/// Each row's (column's) gap across the wrap, `period − last.x1 + first.x0`, is at least the gap its
/// pair needs ([`gap_for`], as between any two lines), the tightest pair's no more than the lattice's
/// rounding of the world's side over it, and none wider than a stitched gap on that axis plus a leaf
/// (the stitched ones round each line's origin up to one).
#[test]
fn the_join_across_the_wrap_is_as_wide_as_a_stitched_join() {
    let root = scratch("world");
    let mods = root.join("mods");
    let dirs: Vec<PathBuf> = [("a", 100.0), ("b", 130.0), ("c", 160.0), ("d", 190.0)].iter().map(|(n, b)| tile(&mods, n, 384, *b)).collect();
    let mut p = Params::new("world_md54", "Test world MD54");
    p.threads = 4;
    p.wrap = Some("xz".into());
    let built = build(&dirs, &root.join("out"), &p).unwrap();
    let plan = &built.plan;
    for axis in 0..2 {
        // The lines along this axis: by row for x, by column for z, each in layout order.
        let mut lines: std::collections::BTreeMap<usize, Vec<usize>> = Default::default();
        for (t, pl) in plan.placed.iter().enumerate() {
            let (c, r) = pl.cell;
            lines.entry(if axis == 0 { r } else { c }).or_default().push(t);
        }
        let mut stitched = 0.0f64;
        let mut wrap = Vec::new();
        for run in lines.values_mut() {
            run.sort_by(|&a, &b| plan.sources[a].rect[axis].total_cmp(&plan.sources[b].rect[axis]));
            for w in run.windows(2) {
                stitched = stitched.max(plan.sources[w[1]].rect[axis] - plan.sources[w[0]].rect[axis + 2]);
            }
            let (first, last) = (&plan.sources[run[0]], &plan.sources[*run.last().unwrap()]);
            let room = |src: &stitch::Source, e: usize| src.gates[e] - (plan.spacing + 2.0 * p.fade);
            let dh = last.ring.edge_mean(axis + 2) - first.ring.edge_mean(axis);
            let need = gap_for(dh, &p, room(last, axis + 2) + room(first, axis), plan.widen);
            wrap.push((plan.period[axis] - last.rect[axis + 2] + first.rect[axis], need));
        }
        println!("axis {axis}: period {} ft, stitched joins up to {stitched} ft, across the wrap (gap, need) {wrap:?} ft", plan.period[axis]);
        assert!(stitched > 0.0);
        // The axis has one period, so the pair needing the most sets it and the others have room over.
        let slack = wrap.iter().map(|(g, need)| g - need).fold(f64::INFINITY, f64::min);
        assert!((0.0..=2.0 * plan.spacing).contains(&slack), "axis {axis}: the wrap's tightest pair has {slack} ft over its need");
        for (g, need) in wrap {
            assert!(g >= need, "axis {axis}: {g} ft across the wrap, its pair needs {need} ft");
            assert!(g <= stitched + 16.0 * plan.spacing, "axis {axis}: {g} ft across the wrap against {stitched} ft stitched");
            assert!(g >= p.min_gap, "axis {axis}: {g} ft across the wrap, under the {} ft least gap", p.min_gap);
        }
    }
}
