//! MD70: an ultra map's own new ground between whole worlds carries the nearest worlds' relief, as
//! MD57 gave a world's far joins its maps', and every seam still meets.

use ps2_float::F;
use std::path::{Path, PathBuf};
use stitch::build::{Params, build};

fn scratch(name: &str) -> PathBuf {
    let d = Path::new(env!("CARGO_TARGET_TMPDIR")).join("stitch-ultra-relief").join(name);
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

/// A berm rising 45 ft over the outer 240 ft of every side, on ground at `base` with hills `hill` ft
/// high about 900 ft across.
fn height(x: f64, z: f64, side: f64, base: f64, hill: f64) -> f64 {
    let d = x.min(z).min(side - x).min(side - z);
    let berm = if d < 240.0 { 45.0 * (1.0 - d / 240.0).powi(2) } else { 0.0 };
    base + hill * (x / 150.0).sin() * (z / 170.0).cos() + berm
}

/// A generated track mod `elev_md70_<name>`: 513 samples a side at 4.5 ft.
fn tile(root: &Path, name: &str, base: f64, hill: f64, surface: u8) -> PathBuf {
    let id = format!("elev_md70_{name}");
    let dir = root.join(&id);
    std::fs::create_dir_all(&dir).unwrap();
    let (n, s) = (512u32, 4.5f32);
    let side = f64::from(n) * f64::from(s);
    let w = n + 1;
    let feet: Vec<f32> = (0..w * w)
        .map(|i| height(f64::from(i % w) * f64::from(s), f64::from(i / w) * f64::from(s), side, base, hill) as f32)
        .collect();
    let (mut g, hs) = trnwrite::Grid::from_feet(w, w, &feet, s).unwrap();
    g.surfaces = vec![surface; (w * w) as usize];
    let trn = trnwrite::build(&g, &trnwrite::Options::new(s, hs)).unwrap();
    let (bytes, _) = trnwrite::write(&trn).unwrap();
    std::fs::write(dir.join(format!("{id}.ps2.trn")), bytes).unwrap();
    let mid = (side / 2.0) as f32;
    let scene = trnwrite::scene::SceneText::for_terrain(&trn, &id, [mid, base as f32, mid], [0.0, 0.0, 1.0]).to_text();
    std::fs::write(dir.join(format!("{id}.scn")), scene).unwrap();
    std::fs::write(
        dir.join("mod.json"),
        format!(
            r#"{{"standard": 1, "kind": "track", "id": "{id}", "name": "Test {name}",
 "source": {{"game": "Real elevation", "data": "generated by stitch's tests", "date": "2026-11-04"}},
 "version": "1.0.0", "author": "stitch tests", "permission": "public-domain",
 "todo": ["generated test map"]}}"#
        ),
    )
    .unwrap();
    dir
}

/// A world of two of those tiles.
fn world(root: &Path, id: &str, tiles: &[(&str, f64, f64, u8)]) -> PathBuf {
    let mods = root.join("tiles");
    let dirs: Vec<PathBuf> = tiles.iter().map(|(n, b, h, s)| tile(&mods, n, *b, *h, *s)).collect();
    let mut p = Params::new(id, &format!("Test {id}"));
    p.threads = 4;
    build(&dirs, &root.join("worlds"), &p).unwrap().dir
}

/// The standard deviation of heights on a square grid after the best plane through them is taken off.
fn spread(h: &[[f64; 3]]) -> f64 {
    let n = h.len() as f64;
    let m = |f: &dyn Fn(&[f64; 3]) -> f64| h.iter().map(f).sum::<f64>() / n;
    let (mx, mz, my) = (m(&|p| p[0]), m(&|p| p[2]), m(&|p| p[1]));
    let (sxx, szz, sxz) = (m(&|p| (p[0] - mx).powi(2)), m(&|p| (p[2] - mz).powi(2)), m(&|p| (p[0] - mx) * (p[2] - mz)));
    let (sxy, szy) = (m(&|p| (p[0] - mx) * (p[1] - my)), m(&|p| (p[2] - mz) * (p[1] - my)));
    let det = sxx * szz - sxz * sxz;
    let (a, b) = ((sxy * szz - szy * sxz) / det, (szy * sxx - sxy * sxz) / det);
    m(&|p| (p[1] - my - a * (p[0] - mx) - b * (p[2] - mz)).powi(2)).sqrt()
}

/// `v` folded back and forth into `lo..hi`.
fn fold(v: f64, lo: f64, hi: f64) -> f64 {
    let span = hi - lo;
    let t = (v - lo).rem_euclid(2.0 * span);
    lo + if t > span { 2.0 * span - t } else { t }
}

/// Two worlds, one with 12 ft hills and one with 3 ft, 5000 ft apart: on the new ground 2000 ft past
/// the hillier one, the ground the ultra map's files hold has that world's relief, within a factor of
/// two of the spread of the world's own ground where the window folds back into it, where before MD70
/// it was a smooth blend. `stitch check` passes; by every world the ground is the blend's.
#[test]
fn new_ground_far_from_every_world_has_the_nearest_worlds_relief() {
    let root = scratch("far");
    let a = world(&root, "world_hilly", &[("a1", 100.0, 12.0, 1), ("a2", 104.0, 12.0, 3)]);
    let b = world(&root, "world_gentle", &[("b1", 110.0, 3.0, 5), ("b2", 108.0, 3.0, 7)]);
    let mut p = Params::new("world_md70", "Test ultra MD70");
    p.threads = 4;
    p.min_gap = 5000.0;
    let built = stitch::ultra::build(&[a.clone(), b.clone()], &root.join("out"), &p).unwrap();
    let r = stitch::check::check(&built.dir, Some(&root.join("worlds")), None);
    assert!(r.ok(), "check failed:\n{}\nnotes:\n{}", r.fail.join("\n"), r.note.join("\n"));
    assert!(built.far_slope <= 0.5, "{}", built.far_slope);
    let plan = &built.plan;
    assert_eq!(plan.relief_scale, 1.0, "the gentle hills are carried whole");
    let worlds = vec![stitch::ultra::World::load(&a).unwrap(), stitch::ultra::World::load(&b).unwrap()];

    let w = stitch::openmx::load(&built.dir).unwrap();
    let tiled = w.tiled().unwrap();
    let ground = |x: f64, z: f64| f64::from(tiled.at(F(x as f32), F(z as f32)).expect("ground").y.0);
    let window = |x0: f64, z0: f64| -> Vec<[f64; 3]> {
        (0..40).flat_map(|j| (0..40).map(move |i| (x0 + 15.0 * f64::from(i), z0 + 15.0 * f64::from(j)))).map(|(x, z)| [x, ground(x, z), z]).collect()
    };
    let (sa, sb) = (&plan.sources[0], &plan.sources[1]);
    let along = if (sa.rect[2] - sb.rect[0]).abs() > (sa.rect[3] - sb.rect[1]).abs() { 0 } else { 1 };
    let (near, _) = if sa.rect[along] < sb.rect[along] { (sa, sb) } else { (sb, sa) };
    assert_eq!(near.tile, 0, "world_hilly is laid out first");
    let mid = |s: &stitch::Source, ax: usize| (s.rect[ax] + s.rect[ax + 2]) / 2.0;
    let mut o = [0.0; 2];
    o[along] = near.rect[along + 2] + 2000.0;
    o[1 - along] = mid(near, 1 - along) - 300.0;
    let join = window(o[0], o[1]);
    for q in &join {
        let d = plan.sources.iter().map(|s| s.distance(q[0], q[2])).fold(f64::INFINITY, f64::min);
        assert!(d >= 1990.0, "({:.0}, {:.0}) is {d:.0} ft from a world", q[0], q[2]);
    }
    // The same window folded back into world_hilly, read off its own ground there.
    let inside: Vec<[f64; 3]> = join
        .iter()
        .map(|q| {
            let (x, z) = (fold(q[0], near.rect[0], near.rect[2]), fold(q[2], near.rect[1], near.rect[3]));
            [x, ground(x, z), z]
        })
        .collect();
    let (sj, sm) = (spread(&join), spread(&inside));
    println!("new ground 2000 ft out: {sj:.2} ft spread; world_hilly's own there: {sm:.2} ft");
    assert!(sm > 2.0, "the fold lands on world_hilly's hills ({sm:.2} ft)");
    assert!(sj > sm / 2.0 && sj < sm * 2.0, "new ground {sj:.2} ft against world_hilly's {sm:.2} ft");

    // The files hold what the plan computes; without the relief the same ground is the blend, next to
    // no spread at all.
    for q in join.iter().step_by(97) {
        let (h, _) = plan.ground_at(&worlds, q[0], q[2]).unwrap();
        assert!((h - q[1]).abs() < 0.05, "the file's {:.3} against stitch's {h:.3} at ({:.0}, {:.0})", q[1], q[0], q[2]);
    }
    let blend: Vec<[f64; 3]> = join
        .iter()
        .map(|q| {
            let (h, r) = plan.ground_at(&worlds, q[0], q[2]).unwrap();
            [q[0], h - r, q[2]]
        })
        .collect();
    let sbl = spread(&blend);
    assert!(sbl < sm / 10.0, "the blend alone has {sbl:.2} ft of spread there");

    // By every world (within its gates) the ground is the blend's to the bit.
    for s in &plan.sources {
        for (x, z) in [(s.rect[2] + 50.0, mid(s, 1)), (s.rect[0] - 50.0, mid(s, 1)), (mid(s, 0), s.rect[3] + 50.0)] {
            if let Some((_, r)) = plan.ground_at(&worlds, x, z) {
                assert_eq!(r, 0.0, "relief at ({x:.0}, {z:.0}), {:.0} ft out", s.distance(x, z));
            }
        }
    }
}

/// The installed ultra map's own new ground has relief (`STITCH_ULTRA`, default
/// `out/mods/tracks/world_ultra`): the mean plane-detrended spread of 300 ft windows whose every point
/// is 1000 ft or more from every world (the nearest image on a map that wraps) is printed with its
/// median and held over 1 ft. Before MD70 it was 0.27 ft (median, 195 windows), the blend alone; 3.72 after.
/// `cargo test --release -p stitch --test ultra_relief -- --ignored --nocapture`.
#[test]
#[ignore]
fn the_installed_ultra_maps_far_new_ground_has_relief() {
    let dir = std::env::var_os("STITCH_ULTRA").map(PathBuf::from).unwrap_or_else(|| Path::new(env!("CARGO_MANIFEST_DIR")).join("../../out/mods/tracks/world_ultra"));
    let meta = modcheck::json::Json::parse(&std::fs::read_to_string(dir.join("mod.json")).unwrap()).unwrap();
    let st = meta.get("stitch").unwrap();
    let nums = |j: &modcheck::json::Json| -> Vec<f64> { j.arr().unwrap().iter().filter_map(modcheck::json::Json::num).collect() };
    let rects: Vec<Vec<f64>> = st.get("worlds").and_then(modcheck::json::Json::arr).unwrap().iter().map(|w| nums(w.get("rect").unwrap())).collect();
    let w = stitch::openmx::load(&dir).unwrap();
    let tiled = w.tiled().unwrap();
    let extent = tiled.extent().map(|v| f64::from(v.0));
    let period = [0, 1].map(|a| if w.wrap[a] { extent[a] } else { 0.0 });
    let dist = |x: f64, z: f64| -> f64 {
        let shifts = stitch::build::images(period);
        rects
            .iter()
            .flat_map(|r| shifts.iter().map(move |sh| ((r[0] + sh[0] - x).max(x - r[2] - sh[0]).max(0.0)).hypot((r[1] + sh[1] - z).max(z - r[3] - sh[1]).max(0.0))))
            .fold(f64::INFINITY, f64::min)
    };
    let mut spreads = Vec::new();
    let (mut x0, mut z0) = (0.0, 0.0);
    while z0 + 300.0 < extent[1] {
        while x0 + 300.0 < extent[0] {
            let pts: Vec<(f64, f64)> = (0..21).flat_map(|j| (0..21).map(move |i| (x0 + 15.0 * f64::from(i), z0 + 15.0 * f64::from(j)))).collect();
            if pts.iter().all(|&(x, z)| dist(x, z) >= 1000.0) {
                let h: Option<Vec<[f64; 3]>> = pts.iter().map(|&(x, z)| tiled.at(F(x as f32), F(z as f32)).map(|g| [x, f64::from(g.y.0), z])).collect();
                if let Some(h) = h {
                    spreads.push(spread(&h));
                }
            }
            x0 += 600.0;
        }
        (x0, z0) = (0.0, z0 + 600.0);
    }
    assert!(!spreads.is_empty(), "no new ground 1000 ft from every world");
    let mean = spreads.iter().sum::<f64>() / spreads.len() as f64;
    spreads.sort_by(f64::total_cmp);
    let median = spreads[spreads.len() / 2];
    println!("{}: {} windows 1000 ft or more from every world: spread {mean:.2} ft mean, {median:.2} median, {:.2} most", dir.display(), spreads.len(), spreads[spreads.len() - 1]);
    assert!(median > 1.0, "the far new ground is the blend alone ({median:.2} ft median)");
}
