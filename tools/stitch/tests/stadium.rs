//! A track in a category other than free ride (a stadium or FMX arena, user 2026-10-22) is never a world's tile.

use std::path::{Path, PathBuf};

fn scratch(name: &str) -> PathBuf {
    let d = Path::new(env!("CARGO_TARGET_TMPDIR")).join("stitch-stadium").join(name);
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

/// A small generated track mod, its mod.json given `extra` fields.
fn tile(root: &Path, id: &str, extra: &str) -> PathBuf {
    let dir = root.join(id);
    std::fs::create_dir_all(&dir).unwrap();
    let (w, s) = (65u32, 4.5f32);
    let feet = vec![100.0f32; (w * w) as usize];
    let (g, hs) = trnwrite::Grid::from_feet(w, w, &feet, s).unwrap();
    let trn = trnwrite::build(&g, &trnwrite::Options::new(s, hs)).unwrap();
    let (bytes, _) = trnwrite::write(&trn).unwrap();
    std::fs::write(dir.join(format!("{id}.ps2.trn")), bytes).unwrap();
    let scene = trnwrite::scene::SceneText::for_terrain(&trn, id, [100.0, 100.0, 100.0], [0.0, 0.0, 1.0]).to_text();
    std::fs::write(dir.join(format!("{id}.scn")), scene).unwrap();
    std::fs::write(
        dir.join("mod.json"),
        format!(
            r#"{{"standard": 1, "kind": "track", "id": "{id}", "name": "Test",
 "source": {{"game": "Real elevation", "data": "generated by stitch's tests", "date": "2026-10-22"}},
 "version": "1.0.0", "author": "stitch tests", "permission": "public-domain",{extra}
 "todo": ["generated test map"]}}"#
        ),
    )
    .unwrap();
    dir
}

#[test]
fn a_stadium_is_refused_as_a_tile() {
    let root = scratch("refused");
    let fmx = tile(&root, "elev_fmx_arena", r#" "category": "stadium", "shootoff": false,"#);
    let err = stitch::Tile::load(&fmx).err().expect("an FMX arena is refused");
    assert!(err.contains("category \"stadium\""), "{err}");
    let open = tile(&root, "elev_fmx_open", r#" "category": "freeride","#);
    stitch::Tile::load(&open).expect("category freeride is a tile as before");
    let plain = tile(&root, "elev_fmx_plain", "");
    stitch::Tile::load(&plain).expect("no category is a tile as before");
}
